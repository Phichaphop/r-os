<?php

declare(strict_types=1);

namespace Blue\Core\Ui;

use RuntimeException;

/**
 * Publishes the design system (ui/) into public/assets/ui — no build tool needed (ADR-006).
 * - app.css = tokens → base → every component's CSS, concatenated in a fixed order (one request)
 * - js/, icons/, fonts/ copied as-is (self-hosted, no CDN — P0-02 §11)
 */
final class AssetPublisher
{
    private const CSS_ORDER = [
        'tokens/primitives.css',
        'tokens/semantic-light.css',
        'tokens/semantic-dark.css',
        'tokens/density.css',
        'base/fonts.css',
        'base/reset.css',
        'base/typography.css',
        'base/layout.css',
        'base/a11y.css',
        'tokens/theme-swatches.css',
    ];

    public function __construct(private readonly string $root)
    {
    }

    /**
     * Cheap fingerprint of the ui/ sources (paths, sizes, modification times). Copying a new release over an old
     * one (XAMPP / FTP) changes it, so the published bundle is rebuilt instead of serving stale CSS/JS.
     */
    public function fingerprint(): string
    {
        $parts = [];
        $it = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($this->root . '/ui', \FilesystemIterator::SKIP_DOTS));
        foreach ($it as $f) {
            /** @var \SplFileInfo $f */
            $parts[] = substr($f->getPathname(), strlen($this->root)) . ':' . $f->getSize() . ':' . $f->getMTime();
        }
        sort($parts);
        return hash('sha256', implode('|', $parts));
    }

    public function isCurrent(): bool
    {
        $stamp = $this->root . '/public/assets/ui/.fingerprint';
        return is_file($this->root . '/public/assets/ui/app.css') && is_file($stamp) && trim((string) file_get_contents($stamp)) === $this->fingerprint();
    }

    public function publish(): int
    {
        $src = $this->root . '/ui';
        $dst = $this->root . '/public/assets/ui';
        $this->rmTree($dst);
        $this->mkdir($dst);

        $css = "/* Blue OS Design System — generated by bin/blue assets:publish. Edit files in ui/, not this file. */\n";
        foreach (self::CSS_ORDER as $f) {
            $css .= "\n/* --- {$f} --- */\n" . $this->read($src . '/' . $f);
        }
        // the system's own components (components/blue) come after the generic ones so they can refine them —
        // kept explicit since the 0.37.0 rename (ros → blue) changed the alphabetical order
        $components = glob($src . '/components/*/*.css') ?: [];
        usort($components, static fn (string $a, string $b): int => [str_contains($a, '/components/blue/'), $a] <=> [str_contains($b, '/components/blue/'), $b]);
        foreach ($components as $f) {
            $css .= "\n/* --- " . substr($f, strlen($src) + 1) . " --- */\n" . $this->read($f);
        }
        foreach (glob($src . '/patterns/*/*.css') ?: [] as $f) {
            $css .= "\n/* --- " . substr($f, strlen($src) + 1) . " --- */\n" . $this->read($f);
        }
        file_put_contents($dst . '/app.css', $css);
        $count = 1;
        file_put_contents($dst . '/.fingerprint', $this->fingerprint());

        foreach (['js', 'icons', 'fonts'] as $dir) {
            $count += $this->copyTree($src . '/' . $dir, $dst . '/' . $dir);
        }
        foreach (glob($src . '/components/*/*.js') ?: [] as $f) {
            $this->mkdir($dst . '/js/components');
            copy($f, $dst . '/js/components/' . basename($f));
            $count++;
        }
        return $count;
    }

    private function read(string $file): string
    {
        $s = file_get_contents($file);
        if ($s === false) {
            throw new RuntimeException("Missing UI file: {$file}");
        }
        return $s;
    }

    private function copyTree(string $from, string $to): int
    {
        if (!is_dir($from)) {
            return 0;
        }
        $n = 0;
        $this->mkdir($to);
        foreach (scandir($from) ?: [] as $name) {
            if ($name === '.' || $name === '..' || $name === '.htaccess') {
                continue;
            }
            $a = $from . '/' . $name;
            $b = $to . '/' . $name;
            if (is_dir($a)) {
                $n += $this->copyTree($a, $b);
            } else {
                copy($a, $b);
                $n++;
            }
        }
        return $n;
    }

    private function mkdir(string $d): void
    {
        if (!is_dir($d) && !mkdir($d, 0755, true) && !is_dir($d)) {
            throw new RuntimeException("Cannot create {$d}");
        }
    }

    private function rmTree(string $d): void
    {
        if (!is_dir($d)) {
            return;
        }
        foreach (scandir($d) ?: [] as $name) {
            if ($name === '.' || $name === '..') {
                continue;
            }
            $p = $d . '/' . $name;
            is_dir($p) ? $this->rmTree($p) : unlink($p);
        }
        rmdir($d);
    }
}
