import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell' });
const out = [];
const check = (name, ok) => out.push(`${ok ? 'PASS' : 'FAIL'}  ${name}`);
let p = await (await b.newContext({ viewport: { width: 1366, height: 900 } })).newPage();
await p.goto('http://127.0.0.1:8080/system/ui-showcase', { waitUntil: 'networkidle' });
await p.keyboard.press('Tab');
check('first Tab lands on skip link', await p.evaluate(() => document.activeElement.classList.contains('skip-link')));
await p.keyboard.press('Enter');
check('skip link moves focus to main', await p.evaluate(() => location.hash === '#main'));
await p.focus('#tab-1'); await p.keyboard.press('ArrowRight');
check('tabs: ArrowRight selects next tab + shows panel', await p.evaluate(() => document.activeElement.id === 'tab-2' && !document.getElementById('tp-2').hidden && document.getElementById('tp-1').hidden));
await p.keyboard.press('End');
check('tabs: End jumps to last', await p.evaluate(() => document.activeElement.id === 'tab-3'));
const opener = p.locator('[data-open-dialog="dlg-l3"]');
await opener.focus(); await p.keyboard.press('Enter');
check('dialog opens as modal', await p.evaluate(() => document.getElementById('dlg-l3').open));
await p.keyboard.press('Escape');
check('Esc closes dialog and focus returns to opener', await p.evaluate(() => !document.getElementById('dlg-l3').open && document.activeElement.dataset.openDialog === 'dlg-l3'));
await p.click('[data-action="toggle-theme"] >> nth=0');
const th = await p.evaluate(() => document.documentElement.dataset.theme);
await p.reload({ waitUntil: 'networkidle' });
check('theme toggle persists across reload', await p.evaluate((t) => document.documentElement.dataset.theme === t, th));
await p.click('label[for="d-comp"]');
check('density compact changes row height token', await p.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--row-height').trim() === '32px'));
await p.click('[data-toast="บันทึกร่างแล้ว"]');
check('toast appears in polite live region', await p.evaluate(() => document.querySelector('.toast-region[aria-live="polite"] .toast')?.textContent.includes('บันทึกร่างแล้ว') === true));
await p.click('[data-action="collapse-sidebar"]');
check('sidebar collapses to rail (64px)', await p.evaluate(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 64));
p = await (await b.newContext({ viewport: { width: 768, height: 900 } })).newPage();
await p.goto('http://127.0.0.1:8080/', { waitUntil: 'networkidle' });
check('tablet: sidebar hidden as drawer', await p.evaluate(() => document.querySelector('.sidebar').getBoundingClientRect().right <= 0));
await p.click('[data-action="open-drawer"]');
await p.waitForTimeout(300);
check('tablet: menu button opens drawer', await p.evaluate(() => document.querySelector('.sidebar').getBoundingClientRect().left >= 0));
await p.keyboard.press('Escape'); await p.waitForTimeout(300);
check('tablet: Esc closes drawer', await p.evaluate(() => document.querySelector('.shell').dataset.drawer === 'closed'));
await b.close();
console.log(out.join('\n'));
