<?php
/**
 * One request: status, lines, the request's QR + barcode (0.38.0 — the pick-up code for the requester once approved),
 * a print button, cancel / confirm receipt / request again,
 * and the history.
 * @var callable $e @var callable $t @var callable $ui @var callable $url @var callable $date @var array<string, mixed> $v
 * @var array<string, mixed> $rq @var ?string $qr @var ?string $qrLink @var bool $pickup @var ?string $barcode @var array<string, string> $errors @var array<string, mixed> $old
 * @var string $here @var bool $canIssue @var bool $canManage
 */
$csrf = '<input type="hidden" name="_csrf" value="' . $e($v['csrf'] ?? '') . '">';
$st = (string) $rq['status'];
$pid = (string) $rq['public_id'];
$dt = static fn (?string $x): string => $x === null ? '—' : $date(substr($x, 0, 10), false) . ' ' . substr($x, 11, 5);
?>
<?= $ui('page-header', ['title' => $t('requisition.request_title', ['ref' => (string) ($rq['ref'] ?? '—')]), 'subtitle' => $rq['requester_name'] . ' · ' . $rq['site_code'] . ($rq['dept_code'] !== null ? ' · ' . $rq['dept_code'] : ''),
    'crumbs' => [[$t('requisition.title'), $url('/requisition')], [$t('requisition.tab.mine'), $url('/requisition/mine')], [(string) ($rq['ref'] ?? '—'), null]]]) ?>
<?php include __DIR__ . '/_nav.php'; ?>
<?php if ($errors !== []): ?><?= $ui('alert', ['tone' => 'danger', 'title' => $t('form.has_errors')]) ?><?php endif; ?>
<div class="grid grid--2">
  <section class="card stack-sm" aria-labelledby="rq-s-h">
    <h2 id="rq-s-h" class="card__title"><?= $e($t('requisition.col.status')) ?>: <?php include __DIR__ . '/_status.php'; ?></h2>
    <dl class="facts">
      <div><dt><?= $e($t('requisition.col.submitted')) ?></dt><dd><?= $e($dt($rq['submitted_at'])) ?></dd></div>
      <div><dt><?= $e($t('requisition.col.approved')) ?></dt><dd><?= $e($dt($rq['approved_at'])) ?></dd></div>
      <div><dt><?= $e($t('requisition.col.issued')) ?></dt><dd><?= $e($dt($rq['issued_at'])) ?><?= $rq['issuer_name'] !== null ? $e(' · ' . $rq['issuer_name']) : '' ?></dd></div>
      <div><dt><?= $e($t('requisition.field.note')) ?></dt><dd><?= $e((string) ($rq['note'] ?? '—')) ?></dd></div>
      <?php if ($rq['issue_note'] !== null): ?><div><dt><?= $e($t('requisition.field.issue_note')) ?></dt><dd><?= $e((string) $rq['issue_note']) ?></dd></div><?php endif; ?>
      <?php if ($rq['reason'] !== null): ?><div><dt><?= $e($t('requisition.field.reason')) ?></dt><dd><?= $e((string) $rq['reason']) ?></dd></div><?php endif; ?>
    </dl>
    <?php if ((int) $rq['over_quota'] === 1): ?><p class="text-sm"><?= $ui('badge', ['tone' => 'warning', 'label' => $t('requisition.over_quota_badge')]) ?> <?= $e($t($rq['route'] === 'requisition.special' ? 'requisition.special_note' : 'requisition.over_note')) ?></p><?php endif; ?>
    <?php if ($st === 'pending'): ?><p class="text-sm text-muted"><?= $e($t('requisition.pending_note')) ?></p><?php endif; ?>
  </section>
  <?php if ($qr !== null): ?>
  <section class="card stack-sm rq-pickup rq-slip" aria-labelledby="rq-qr-h">
    <h2 id="rq-qr-h" class="card__title"><?= $e($t($pickup ? 'requisition.pickup_title' : 'requisition.codes_title')) ?></h2>
    <p class="text-sm"><?= $e($t($pickup ? 'requisition.pickup_help' : 'requisition.codes_help')) ?></p>
    <div class="rq-codes">
      <div class="in-qr" role="img" aria-label="<?= $e($t('requisition.qr_alt', ['ref' => (string) $rq['ref']])) ?>"><?= $qr /* generated by QrRender — no user markup */ ?></div>
      <?php if ($barcode !== null): ?><div class="rq-barcode"><?= $barcode /* generated by Code128 — no user markup */ ?></div><?php endif; ?>
    </div>
    <?php if ($pickup): ?><p class="text-sm"><?= $e($t('requisition.pickup_code')) ?> <strong class="rq-code"><?= $e(implode(' ', str_split((string) $rq['pickup_code'], 4))) ?></strong></p><?php endif; ?>
    <div class="row no-print"><?= $ui('button', ['label' => $t('requisition.print_slip'), 'variant' => 'secondary', 'icon' => 'printer', 'attrs' => ['data-print' => '']]) ?></div>
  </section>
  <?php endif; ?>
</div>
<section class="card card--flush" aria-labelledby="rq-lines-h">
  <div class="card__head"><h2 id="rq-lines-h" class="card__title"><?= $e($t('requisition.col.items')) ?></h2></div>
  <?php include __DIR__ . '/_lines.php'; ?>
</section>
<?php if ($rq['mine']): ?>
<section class="card stack-sm" aria-labelledby="rq-a-h">
  <h2 id="rq-a-h" class="card__title"><?= $e($t('requisition.actions')) ?></h2>
  <?php if (in_array($st, ['partial', 'fulfilled'], true)): ?>
  <form method="post" action="<?= $e($url('/requisition/r/' . $pid . '/receive')) ?>"><?= $csrf ?><p class="text-sm"><?= $e($t('requisition.receive_help')) ?></p>
    <?= $ui('button', ['label' => $t('requisition.receive'), 'type' => 'submit', 'variant' => 'primary', 'icon' => 'circle-check']) ?></form>
  <?php endif; ?>
  <?php if (in_array($st, ['pending', 'approved'], true)): ?>
  <form method="post" action="<?= $e($url('/requisition/r/' . $pid . '/cancel')) ?>" class="stack-sm" novalidate><?= $csrf ?>
    <?= $ui('field', ['name' => 'cancel_reason', 'label' => $t('requisition.field.cancel_reason'), 'value' => (string) ($old['cancel_reason'] ?? ''), 'error' => $errors['cancel_reason'] ?? null]) ?>
    <div class="row"><?= $ui('button', ['label' => $t('requisition.cancel'), 'type' => 'submit', 'variant' => 'danger', 'icon' => 'x']) ?></div></form>
  <?php endif; ?>
  <form method="post" action="<?= $e($url('/requisition/r/' . $pid . '/repeat')) ?>"><?= $csrf ?>
    <?= $ui('button', ['label' => $t('requisition.repeat'), 'type' => 'submit', 'variant' => 'secondary', 'icon' => 'refresh']) ?></form>
</section>
<?php elseif ($rq['can_issue'] && $st === 'approved'): ?>
  <p><?= $ui('button', ['label' => $t('requisition.open_desk'), 'href' => $url('/requisition/issue?code=' . rawurlencode((string) $rq['ref'])), 'variant' => 'primary', 'icon' => 'qrcode']) ?></p>
<?php endif; ?>
<section class="card stack-sm" aria-labelledby="rq-h-h">
  <h2 id="rq-h-h" class="card__title"><?= $e($t('requisition.history')) ?></h2>
  <ul class="plain-list stack-sm"><?php foreach ($rq['events'] as $ev): ?><li><?= $e($t('requisition.event.' . $ev['event'])) ?> · <?= $e((string) ($ev['actor_name'] ?? $t('requisition.system'))) ?> <span class="text-sm text-muted"><?= $e($date((string) $ev['created_at'])) ?></span><?= $ev['note'] !== null ? ' — ' . $e((string) $ev['note']) : '' ?></li><?php endforeach; ?></ul>
</section>
